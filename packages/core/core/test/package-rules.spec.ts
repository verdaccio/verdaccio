describe('package rule compatibility', () => {
  test.each(compatibilityCases)('%s matches %s: %s', (pattern, packageName, matches) => {
    const rule = {
      access: ['readers'],
      publish: ['publishers'],
      unpublish: ['maintainers'],
      proxy: ['internal'],
    };
    expect(getMatchedPackagesSpec(packageName, { [pattern]: rule })).toBe(
      matches ? rule : undefined
    );
  });

  test.each([
    [['react', 'r*', '**'], 'react', 'react'],
    [['r*', 'react', '**'], 'react', 'r*'],
    [['**', '@team/*'], '@team/core', '**'],
    [['@team/*', '@*/*', '**'], '@TEAM/Core', '@team/*'],
    [['@team/*', '@*/*', '**'], '@other/core', '@*/*'],
    [['@team/*', '@*/*', '**'], 'react', '**'],
    [['@{team,private}/*', '@*/*'], '@private/core', '@{team,private}/*'],
    [['react{,-dom}', 'react*', '**'], 'react-dom', 'react{,-dom}'],
    [['package-!(private)', 'package-*'], 'package-private', 'package-*'],
    [['!@private/*', '@private/*'], '@private/core', '@private/*'],
  ] as [string[], string, string][])(
    'selects the first rule in %j for %s',
    (patterns, packageName, selected) => {
      const packages: PackageList = Object.fromEntries(
        patterns.map((pattern, index) => [
          pattern,
          {
            access: [`reader-${index}`],
            publish: [`publisher-${index}`],
            unpublish: [`maintainer-${index}`],
            proxy: [`uplink-${index}`],
          },
        ])
      );
      expect(getMatchedPackagesSpec(packageName, packages)).toBe(packages[selected]);
    }
  );

  test('returns no policy when no rule matches', () => {
    expect(
      getMatchedPackagesSpec('@other/core', { '@private/*': { access: ['owner'] } })
    ).toBeUndefined();
  });
});
